  return "现在写本章，材料如下。\n\n【本章细纲】\n" + context.chapterRaw
    + "\n\n【读档包（程序记账的人物状态、伏笔台账、近章摘要与钩子清单）】\n" + context.dossierText
    + "\n\n【相关设定条目（只含本章用到的人物卡、伏笔条目与世界观规矩）】\n" + (context.settingsSlices || "无额外条目，按读档包与细纲执行。")
    + "\n\n【上一章最后 3 段原文】\n" + (context.tail || "本章为第 1 章，此栏为空。")
    + "\n\n【发散等级】" + String(divergence)
    + "\n0 = 严格按细纲；1 = 可补细节；2 = 可调次要情节，需在状态变更里说明；3 = 先提出更好的走向，不写正文。\n\n开始写。只输出章节正文与【状态变更】。";
